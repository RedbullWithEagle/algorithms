func TestBSearch(t *testing.T) {
	type args struct {
		nums   []int
		target int
	}
	tests := []struct {
		name string
		args args
		want int
	}{
		{name: "bseach-1",args: args{nums: []int{2,3,5},target: 3},want: 1},
		{name: "bseach-2",args: args{nums: []int{2,3,5},target: 8},want: -1},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := BSearch(tt.args.nums, tt.args.target); got != tt.want {
				t.Errorf("BSearch() = %v, want %v", got, tt.want)
			}
		})
	}
}

